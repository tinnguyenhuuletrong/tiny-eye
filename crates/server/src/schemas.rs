//! Editor and agent grammars, generated from the sources of truth and written to doc/schema by
//! `make schemas` (`tiny-eye schemas`). tests/schemas.rs fails when a committed file is stale.
//!
//! | File | Generated from |
//! | --- | --- |
//! | tqs.schema.json | `TqsDocument` in api/openapi.yaml |
//! | dashboard.schema.json | `Dashboard` in api/openapi.yaml |
//! | config.schema.json | the config structs + defaults from config/default.yaml |
//! | mcp-tools.json / mcp-tools.md | operations with `x-mcp-tool` in api/openapi.yaml |
//! | tqs-formula.tmLanguage.json | the formula grammar (`tqs::formula::FUNCS`) |

use serde_json::{Value, json};

const BASE_ID: &str = "https://tiny-eye.local/schema";

fn with_header(mut schema: Value, file: &str, title: &str) -> Value {
    if let Value::Object(m) = &mut schema {
        let mut out = serde_json::Map::new();
        out.insert("$schema".into(), json!("https://json-schema.org/draft/2020-12/schema"));
        out.insert("$id".into(), json!(format!("{BASE_ID}/{file}")));
        out.insert("title".into(), json!(title));
        out.insert("$comment".into(), json!("Generated by `make schemas` — do not edit; change the source of truth instead."));
        for (k, v) in std::mem::take(m) {
            out.entry(k).or_insert(v);
        }
        *m = out;
    }
    schema
}

fn pretty(v: &Value) -> String {
    serde_json::to_string_pretty(v).expect("json") + "\n"
}

/// TextMate grammar for TQS formula expressions (VS Code; Monaco via monaco-textmate).
fn formula_grammar() -> Value {
    let funcs = tqs::formula::FUNCS.iter().map(|(n, _, _)| *n).collect::<Vec<_>>().join("|");
    json!({
        "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
        "name": "TQS formula",
        "scopeName": "source.tqs-formula",
        "comment": "Generated by `make schemas` from tqs::formula::FUNCS — do not edit.",
        "patterns": [
            {"name": "support.function.tqs", "match": format!("\\b({funcs})(?=\\s*\\()")},
            {"name": "variable.language.time.tqs", "match": "\\btime\\b"},
            {"name": "constant.numeric.tqs", "match": "\\b\\d+(\\.\\d+)?([eE][-+]?\\d+)?\\b"},
            {"name": "variable.other.query.tqs", "match": "\\b[a-z][a-z0-9_]{0,31}\\b"},
            {"name": "keyword.operator.arithmetic.tqs", "match": "[-+*/]"},
            {"name": "punctuation.tqs", "match": "[(),]"},
            {"name": "invalid.illegal.tqs", "match": "[^\\s]"}
        ]
    })
}

fn mcp_markdown(tools: &Value) -> String {
    let mut md = String::from(
        "# MCP tools\n\nGenerated by `make schemas` from `x-mcp-tool` in api/openapi.yaml — do not edit.\n\n\
         Server: `tiny-eye mcp --url http://<node>:7070 [--token-env VAR]` (stdio). Each tool forwards to the HTTP operation below.\n\n\
         | Tool | HTTP | Description | Input |\n| :--- | :--- | :--- | :--- |\n",
    );
    for (t, op) in tools["tools"].as_array().into_iter().flatten().zip(crate::api::MCP_TOOLS) {
        let props: Vec<String> = t["inputSchema"]["properties"]
            .as_object()
            .map(|p| {
                let req: Vec<&str> =
                    t["inputSchema"]["required"].as_array().map(|r| r.iter().filter_map(Value::as_str).collect()).unwrap_or_default();
                p.keys().map(|k| if req.contains(&k.as_str()) { format!("`{k}`*") } else { format!("`{k}`") }).collect()
            })
            .unwrap_or_default();
        md.push_str(&format!(
            "| `{}` | `{} {}` | {} | {} |\n",
            t["name"].as_str().unwrap_or_default(),
            op.method,
            op.path,
            t["description"].as_str().unwrap_or_default().replace('\n', " "),
            if props.is_empty() { "none".into() } else { props.join(", ") }
        ));
    }
    md.push_str("\n`*` required. Full input schemas: [mcp-tools.json](mcp-tools.json) (the exact `tools/list` result).\n");
    md
}

/// Every generated file: (name under doc/schema, contents).
pub fn generate() -> Vec<(&'static str, String)> {
    let tqs: Value = serde_json::from_str(crate::api::TQS_SCHEMA_JSON).expect("generated schema");
    let dash: Value = serde_json::from_str(crate::api::DASHBOARD_SCHEMA_JSON).expect("generated schema");
    let tools = crate::mcp::tools_list();
    vec![
        ("tqs.schema.json", pretty(&with_header(tqs, "tqs.schema.json", "TQS 3 query document"))),
        ("dashboard.schema.json", pretty(&with_header(dash, "dashboard.schema.json", "tiny-eye dashboard (YAML in git)"))),
        ("config.schema.json", pretty(&with_header(engine::config::json_schema(), "config.schema.json", "tiny-eye configuration"))),
        ("mcp-tools.json", pretty(&tools)),
        ("mcp-tools.md", mcp_markdown(&tools)),
        ("tqs-formula.tmLanguage.json", pretty(&formula_grammar())),
    ]
}

/// Write every generated file into `dir`.
pub fn write(dir: &std::path::Path) -> anyhow::Result<Vec<String>> {
    std::fs::create_dir_all(dir)?;
    let mut written = vec![];
    for (name, body) in generate() {
        std::fs::write(dir.join(name), body)?;
        written.push(name.to_string());
    }
    Ok(written)
}
