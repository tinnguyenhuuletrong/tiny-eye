//! Generates `tables.rs` from `schema/tables.yaml` (the source of truth for stored tables):
//! Arrow schemas, typed rows + builders, and DuckLake DDL. See the YAML header for the format.

#![allow(clippy::unwrap_used)] // a build script should fail loudly

use serde::Deserialize;
use std::collections::BTreeMap;
use std::fmt::Write as _;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct File {
    version: u32,
    tables: BTreeMap<String, Table>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Table {
    #[serde(default)]
    doc: Option<String>,
    sort: Vec<String>,
    time: String,
    columns: Vec<Column>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Column {
    name: String,
    #[serde(rename = "type")]
    ty: String,
    #[serde(default)]
    nullable: bool,
    #[serde(default)]
    encoding: Option<String>,
    #[serde(default)]
    bloom: bool,
}

/// (rust type, arrow builder type, builder constructor, arrow DataType expr, DuckDB type)
fn mapping(ty: &str) -> (&'static str, &'static str, &'static str, &'static str, &'static str) {
    match ty {
        "utf8" => ("String", "StringBuilder", "StringBuilder::new()", "DataType::Utf8", "VARCHAR"),
        "u8" => ("u8", "UInt8Builder", "UInt8Builder::new()", "DataType::UInt8", "UTINYINT"),
        "u32" => ("u32", "UInt32Builder", "UInt32Builder::new()", "DataType::UInt32", "UINTEGER"),
        "u64" => ("u64", "UInt64Builder", "UInt64Builder::new()", "DataType::UInt64", "UBIGINT"),
        "i64" => ("i64", "Int64Builder", "Int64Builder::new()", "DataType::Int64", "BIGINT"),
        "f64" => ("f64", "Float64Builder", "Float64Builder::new()", "DataType::Float64", "DOUBLE"),
        "bool" => ("bool", "BooleanBuilder", "BooleanBuilder::new()", "DataType::Boolean", "BOOLEAN"),
        "timestamp_ns" => (
            "i64",
            "TimestampNanosecondBuilder",
            "TimestampNanosecondBuilder::new()",
            "DataType::Timestamp(TimeUnit::Nanosecond, None)",
            "TIMESTAMP_NS",
        ),
        "date" => ("i32", "Date32Builder", "Date32Builder::new()", "DataType::Date32", "DATE"),
        "trace_id" => ("[u8; 16]", "BinaryBuilder", "BinaryBuilder::new()", "DataType::Binary", "BLOB"),
        "map" => (
            "Labels",
            "MapBuilder<StringBuilder, StringBuilder>",
            "MapBuilder::new(None, StringBuilder::new(), StringBuilder::new())",
            "map_type()",
            "MAP(VARCHAR, VARCHAR)",
        ),
        "utf8_list" => ("Vec<String>", "ListBuilder<StringBuilder>", "ListBuilder::new(StringBuilder::new())", "list_type()", "VARCHAR[]"),
        other => panic!("schema/tables.yaml: unknown column type {other:?}"),
    }
}

fn camel(s: &str) -> String {
    s.split('_').map(|p| p[..1].to_uppercase() + &p[1..]).collect()
}

fn append_stmt(c: &Column) -> String {
    let f = &c.name;
    let b = format!("self.{f}");
    let v = if c.nullable { "v".to_string() } else { format!("row.{f}") };
    let one = match c.ty.as_str() {
        "utf8" => format!("{b}.append_value(&{v})"),
        "trace_id" => format!("{b}.append_value({v})"),
        "map" => format!(
            "{{ for (k, x) in {v}.iter() {{ {b}.keys().append_value(k); {b}.values().append_value(x); }} {b}.append(true).expect(\"map entry\"); }}"
        ),
        "utf8_list" => format!("{{ for x in {v}.iter() {{ {b}.values().append_value(x); }} {b}.append(true); }}"),
        _ => format!("{b}.append_value({v})"),
    };
    if c.nullable {
        let null = match c.ty.as_str() {
            "map" => format!("{b}.append(false).expect(\"map null\")"),
            "utf8_list" => format!("{b}.append(false)"),
            _ => format!("{b}.append_null()"),
        };
        let scrut = if matches!(c.ty.as_str(), "utf8" | "map" | "utf8_list") { format!("&row.{f}") } else { format!("row.{f}") };
        format!("match {scrut} {{ Some(v) => {one}, None => {null} }}")
    } else {
        one
    }
}

fn main() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../schema/tables.yaml");
    println!("cargo:rerun-if-changed={path}");
    let file: File =
        serde_norway::from_str(&std::fs::read_to_string(path).expect("read schema/tables.yaml")).expect("parse schema/tables.yaml");
    let mut o = String::new();
    let w = &mut o;
    writeln!(w, "// @generated by crates/engine/build.rs from schema/tables.yaml — do not edit.\n").unwrap();
    writeln!(w, "pub const SCHEMA_VERSION: u32 = {};\n", file.version).unwrap();
    writeln!(w, "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum Table {{").unwrap();
    for name in file.tables.keys() {
        writeln!(w, "    {},", camel(name)).unwrap();
    }
    writeln!(w, "}}\n").unwrap();

    let arm = |w: &mut String, f: &dyn Fn(&str, &Table) -> String| {
        for (name, t) in &file.tables {
            writeln!(w, "            Table::{} => {},", camel(name), f(name, t)).unwrap();
        }
    };
    let strs = |v: Vec<&str>| format!("&[{}]", v.iter().map(|s| format!("{s:?}")).collect::<Vec<_>>().join(", "));

    writeln!(w, "impl Table {{").unwrap();
    writeln!(
        w,
        "    pub const ALL: [Table; {}] = [{}];",
        file.tables.len(),
        file.tables.keys().map(|n| format!("Table::{}", camel(n))).collect::<Vec<_>>().join(", ")
    )
    .unwrap();
    writeln!(w, "    pub fn name(self) -> &'static str {{\n        match self {{").unwrap();
    arm(w, &|n, _| format!("{n:?}"));
    writeln!(w, "        }}\n    }}").unwrap();
    writeln!(w, "    pub fn from_name(name: &str) -> Option<Table> {{ Table::ALL.into_iter().find(|t| t.name() == name) }}").unwrap();
    writeln!(w, "    pub fn doc(self) -> &'static str {{\n        match self {{").unwrap();
    arm(w, &|_, t| format!("{:?}", t.doc.clone().unwrap_or_default()));
    writeln!(w, "        }}\n    }}").unwrap();
    writeln!(
        w,
        "    /// Row order inside every Parquet file.\n    pub fn sort_columns(self) -> &'static [&'static str] {{\n        match self {{"
    )
    .unwrap();
    arm(w, &|_, t| strs(t.sort.iter().map(String::as_str).collect()));
    writeln!(w, "        }}\n    }}").unwrap();
    writeln!(
        w,
        "    /// Column that decides a row's hour partition.\n    pub fn time_column(self) -> &'static str {{\n        match self {{"
    )
    .unwrap();
    arm(w, &|_, t| format!("{:?}", t.time));
    writeln!(w, "        }}\n    }}").unwrap();
    writeln!(w, "    /// SQL for the unix hour of a row (partition key), from the time column's type.\n    pub fn hour_sql(self) -> &'static str {{\n        match self {{").unwrap();
    arm(w, &|_, t| {
        let c = t.columns.iter().find(|c| c.name == t.time).unwrap_or_else(|| panic!("time column {} missing", t.time));
        match c.ty.as_str() {
            "i64" => format!("{:?}", format!("({} // 3600000)", c.name)),
            // DuckDB 2.0.1: `epoch_ms(TIMESTAMP_NS) // n` raises a spurious cast error; epoch_ns works.
            "timestamp_ns" => format!("{:?}", format!("(epoch_ns({}) // 3600000000000)", c.name)),
            other => panic!("time column {} has type {other}; use i64 (ms) or timestamp_ns", c.name),
        }
    });
    writeln!(w, "        }}\n    }}").unwrap();
    writeln!(w, "    pub fn column_names(self) -> &'static [&'static str] {{\n        match self {{").unwrap();
    arm(w, &|_, t| strs(t.columns.iter().map(|c| c.name.as_str()).collect()));
    writeln!(w, "        }}\n    }}").unwrap();
    for (fname, pred) in [("bloom_columns", "bloom"), ("delta_columns", "delta"), ("byte_stream_split_columns", "byte_stream_split")] {
        writeln!(w, "    pub fn {fname}(self) -> &'static [&'static str] {{\n        match self {{").unwrap();
        arm(w, &|_, t| {
            strs(
                t.columns
                    .iter()
                    .filter(|c| if pred == "bloom" { c.bloom } else { c.encoding.as_deref() == Some(pred) })
                    .map(|c| c.name.as_str())
                    .collect(),
            )
        });
        writeln!(w, "        }}\n    }}").unwrap();
    }
    writeln!(w, "    /// DuckDB column list, e.g. `tenant VARCHAR, region VARCHAR, …`.\n    pub fn ddl_columns(self) -> &'static str {{\n        match self {{").unwrap();
    arm(w, &|_, t| format!("{:?}", t.columns.iter().map(|c| format!("{} {}", c.name, mapping(&c.ty).4)).collect::<Vec<_>>().join(", ")));
    writeln!(w, "        }}\n    }}").unwrap();
    writeln!(w, "    pub fn ddl(self, qualified_name: &str) -> String {{ format!(\"CREATE TABLE IF NOT EXISTS {{qualified_name}} ({{}})\", self.ddl_columns()) }}").unwrap();
    writeln!(w, "    pub fn schema(self) -> SchemaRef {{\n        match self {{").unwrap();
    arm(w, &|n, _| format!("{}_schema()", n));
    writeln!(w, "        }}\n    }}").unwrap();
    writeln!(w, "}}\n").unwrap();

    for (name, t) in &file.tables {
        let cn = camel(name);
        // schema
        writeln!(w, "fn {name}_schema() -> SchemaRef {{\n    static S: std::sync::LazyLock<SchemaRef> = std::sync::LazyLock::new(|| {{\n        Arc::new(Schema::new(vec![").unwrap();
        for c in &t.columns {
            writeln!(w, "            Field::new({:?}, {}, {}),", c.name, mapping(&c.ty).3, c.nullable).unwrap();
        }
        writeln!(w, "        ]).with_metadata(std::collections::HashMap::from([(\"schema_version\".to_string(), SCHEMA_VERSION.to_string())])))\n    }});\n    S.clone()\n}}\n").unwrap();
        // row
        if let Some(d) = &t.doc {
            writeln!(w, "/// {d}").unwrap();
        }
        writeln!(w, "#[derive(Clone, Debug, Default, PartialEq)]\npub struct {cn}Row {{").unwrap();
        for c in &t.columns {
            let rt = mapping(&c.ty).0;
            if c.nullable {
                writeln!(w, "    pub {}: Option<{rt}>,", c.name).unwrap();
            } else {
                writeln!(w, "    pub {}: {rt},", c.name).unwrap();
            }
        }
        writeln!(w, "}}\n").unwrap();
        // builder
        writeln!(w, "pub struct {cn}Builder {{").unwrap();
        for c in &t.columns {
            writeln!(w, "    {}: {},", c.name, mapping(&c.ty).1).unwrap();
        }
        writeln!(w, "    rows: usize,\n}}\n").unwrap();
        writeln!(w, "impl Default for {cn}Builder {{\n    fn default() -> Self {{\n        Self {{").unwrap();
        for c in &t.columns {
            writeln!(w, "            {}: {},", c.name, mapping(&c.ty).2).unwrap();
        }
        writeln!(w, "            rows: 0,\n        }}\n    }}\n}}\n").unwrap();
        writeln!(w, "impl {cn}Builder {{").unwrap();
        writeln!(w, "    pub fn append(&mut self, row: &{cn}Row) {{").unwrap();
        for c in &t.columns {
            writeln!(w, "        {};", append_stmt(c)).unwrap();
        }
        writeln!(w, "        self.rows += 1;\n    }}").unwrap();
        writeln!(w, "    pub fn len(&self) -> usize {{ self.rows }}").unwrap();
        writeln!(w, "    pub fn is_empty(&self) -> bool {{ self.rows == 0 }}").unwrap();
        writeln!(w, "    pub fn finish(&mut self) -> RecordBatch {{\n        let cols: Vec<ArrayRef> = vec![").unwrap();
        for c in &t.columns {
            writeln!(w, "            Arc::new(self.{}.finish()),", c.name).unwrap();
        }
        writeln!(w, "        ];\n        self.rows = 0;\n        RecordBatch::try_new({name}_schema(), cols).expect(\"generated schema matches builders\")\n    }}\n}}\n").unwrap();
    }
    let out = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("tables.rs");
    std::fs::write(out, o).unwrap();
}
